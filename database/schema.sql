-- ReturnWise SQLite Schema
-- All tables used by the application.
-- Run via db.py on first start.

PRAGMA foreign_keys = ON;

-- ============================================================
-- Products
-- ============================================================
CREATE TABLE IF NOT EXISTS products (
    product_id      TEXT PRIMARY KEY,
    name            TEXT NOT NULL,
    category        TEXT NOT NULL,   -- e.g. electronics, clothing, digital, ...
    unit_price      REAL NOT NULL,
    returnable      INTEGER NOT NULL DEFAULT 1,  -- 0 = non-returnable
    return_window_days INTEGER NOT NULL DEFAULT 30
);

-- ============================================================
-- Customers (fictional – no real PII)
-- ============================================================
CREATE TABLE IF NOT EXISTS customers (
    customer_id     TEXT PRIMARY KEY,
    name            TEXT NOT NULL,
    email           TEXT NOT NULL    -- fictional addresses only
);

-- ============================================================
-- Orders
-- ============================================================
CREATE TABLE IF NOT EXISTS orders (
    order_id        TEXT PRIMARY KEY,
    customer_id     TEXT NOT NULL REFERENCES customers(customer_id),
    product_id      TEXT NOT NULL REFERENCES products(product_id),
    quantity        INTEGER NOT NULL DEFAULT 1,
    unit_price      REAL NOT NULL,   -- price at time of order
    total_amount    REAL NOT NULL,   -- quantity * unit_price
    order_date      TEXT NOT NULL,   -- ISO 8601 date string (YYYY-MM-DD)
    delivery_date   TEXT,            -- NULL if not yet delivered
    status          TEXT NOT NULL    -- pending | processing | delivered | cancelled | returned
);

-- ============================================================
-- Return Policies (one per product category)
-- Supplements the JSON policy file with queryable records.
-- ============================================================
CREATE TABLE IF NOT EXISTS return_policies (
    policy_id           TEXT PRIMARY KEY,
    category            TEXT NOT NULL UNIQUE,
    return_window_days  INTEGER NOT NULL,
    returnable          INTEGER NOT NULL DEFAULT 1,
    replacement_only    INTEGER NOT NULL DEFAULT 0,  -- 1 = no cash refund, replacement only
    damaged_allowed     INTEGER NOT NULL DEFAULT 1,  -- 1 = damaged-item claims accepted
    notes               TEXT
);

-- ============================================================
-- Return Requests  (submitted via Streamlit)
-- ============================================================
CREATE TABLE IF NOT EXISTS return_requests (
    request_id      TEXT PRIMARY KEY,   -- UUID generated by the service layer
    order_id        TEXT NOT NULL,      -- may reference a non-existent order (test cases)
    reason          TEXT NOT NULL,      -- defective | wrong_item | changed_mind | damaged | other
    description     TEXT,
    submitted_at    TEXT NOT NULL,      -- ISO 8601 datetime string
    status          TEXT NOT NULL DEFAULT 'pending',  -- pending | validated | manual_review | failed (legacy: approved | rejected)
    is_test         INTEGER NOT NULL DEFAULT 0,       -- 1 when triggered from test/demo mode
    client_token    TEXT,               -- per-form-submission token: stops duplicate requests
    error_message   TEXT                -- set when processing failed (status = 'failed')
);

-- ============================================================
-- Agent Execution Logs
-- One row per workflow step, per request (includes skipped steps and the correction loop).
-- ============================================================
CREATE TABLE IF NOT EXISTS agent_logs (
    log_id          INTEGER PRIMARY KEY AUTOINCREMENT,
    request_id      TEXT NOT NULL REFERENCES return_requests(request_id),
    agent_name      TEXT NOT NULL,
    agent_role      TEXT NOT NULL,
    execution_order INTEGER NOT NULL,
    status          TEXT NOT NULL,   -- success | error | skipped
    input_summary   TEXT,
    output_summary  TEXT,
    explanation     TEXT,
    executed_at     TEXT NOT NULL,   -- ISO 8601 datetime string
    step_type       TEXT NOT NULL DEFAULT 'agent',  -- agent | validation | correction | revalidation | skipped
    verdict         TEXT,            -- eligibility / action / validation_status produced by the step
    input_json      TEXT,            -- full structured input passed to the agent
    output_json     TEXT             -- full structured output returned by the agent
);

-- ============================================================
-- Final Recommendations
-- One row per request (updated in-place if corrected).
-- ============================================================
CREATE TABLE IF NOT EXISTS recommendations (
    recommendation_id   TEXT PRIMARY KEY,   -- UUID
    request_id          TEXT NOT NULL UNIQUE REFERENCES return_requests(request_id),
    order_id            TEXT NOT NULL,
    eligibility_status  TEXT NOT NULL,      -- eligible | ineligible | manual_review
    recommended_action  TEXT NOT NULL,      -- refund | replacement | reject | manual_review
    refund_amount       REAL,               -- NULL when action is not refund
    policy_explanation  TEXT,
    validation_status   TEXT NOT NULL DEFAULT 'pending',  -- pending | passed | failed | manual_review
    validation_details  TEXT,
    correction_attempted INTEGER NOT NULL DEFAULT 0,       -- 0 or 1
    correction_details  TEXT,
    created_at          TEXT NOT NULL,
    updated_at          TEXT NOT NULL
);
